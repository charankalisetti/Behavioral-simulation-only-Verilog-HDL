// ============================================================================
// Module Name: bell_triangle
// Description: Builds and prints the complete Bell Triangle from Row 0 to Row n
//              (n = 5 -> 6 rows total) using a 2D integer array `bell[9:0][9:0]`.
// ============================================================================

module bell_triangle;

    integer n = 5;                  // Maximum row index to generate (builds rows 0 to 5)
    integer bell [9:0][9:0];        // 10x10 2D array storing every row and column value

    initial begin : block
        integer r, c;               // r = row index, c = column index

        // 1. Initialize and print Row 0 (the apex of the Bell Triangle)
        bell[0][0] = 1;
        $display("%0d", bell[0][0]);

        // 2. Outer loop: Build and print Rows r = 1 through r = 5
        for (r = 1; r <= n; r = r + 1) begin

            // Rule A: First element of row 'r' copies the LAST element of row 'r-1'
            bell[r][0] = bell[r - 1][r - 1];

            // Start a new line and print the first number of row 'r' without a newline
            $display(" ");
            $write("%0d", bell[r][0]);

            // Rule B: Inner loop fills columns c = 1 up to c = r
            for (c = 1; c <= r; c = c + 1) begin
                // Current cell = (Left cell in current row) + (Up-Left cell in prev row)
                bell[r][c] = bell[r][c - 1] + bell[r - 1][c - 1];

                // Print comma followed by the newly computed cell on the same line
                $write(",%0d", bell[r][c]);
            end
        end
    end

endmodule

